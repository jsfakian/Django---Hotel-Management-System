export const BookingLangContext = createContext({
  lang: 'en',
  t: (k) => k,
  toggleLang: () => {},
})

export function readStoredLang() {
  try {
    const v = localStorage.getItem(LANG_KEY)
    return v === 'el' ? 'el' : 'en'
  } catch {
    return 'en'
  }
}

export function useBookingT() {
  return useContext(BookingLangContext)
}
