import matplotlib.pyplot as plt
import networkx as nx

# Δημιουργία γραφήματος
G = nx.DiGraph()

# Κόμβοι (Κλάσεις - Interfaces)
interfaces = [
    "Διαχείριση Χρηστών", "Διαχείριση Καταλυμάτων", "Διαχείριση Δωματίων",
    "Διαχείριση Επισκεπτών", "Διαχείριση Εργαζομένων", "Υπηρεσίες Δωματίου",
    "Διαχείριση Κρατήσεων", "Διαχείριση Συμβολαίων", "Μηχανή Τιμολόγησης (AI)",
    "Πληρωμές & Τιμολόγια", "Ειδοποιήσεις & Επικοινωνία", "Εξωτερικά APIs"
]

# Προσθήκη κόμβων
G.add_nodes_from(interfaces)

# Συνδέσεις μεταξύ των λειτουργιών
edges = [
    ("Διαχείριση Χρηστών", "Διαχείριση Κρατήσεων"),
    ("Διαχείριση Χρηστών", "Πληρωμές & Τιμολόγια"),
    ("Διαχείριση Καταλυμάτων", "Διαχείριση Δωματίων"),
    ("Διαχείριση Καταλυμάτων", "Διαχείριση Κρατήσεων"),
    ("Διαχείριση Δωματίων", "Διαχείριση Κρατήσεων"),
    ("Διαχείριση Επισκεπτών", "Διαχείριση Κρατήσεων"),
    ("Διαχείριση Εργαζομένων", "Υπηρεσίες Δωματίου"),
    ("Υπηρεσίες Δωματίου", "Διαχείριση Κρατήσεων"),
    ("Διαχείριση Κρατήσεων", "Διαχείριση Συμβολαίων"),
    ("Διαχείριση Κρατήσεων", "Μηχανή Τιμολόγησης (AI)"),
    ("Διαχείριση Συμβολαίων", "Μηχανή Τιμολόγησης (AI)"),
    ("Διαχείριση Κρατήσεων", "Πληρωμές & Τιμολόγια"),
    ("Πληρωμές & Τιμολόγια", "Εξωτερικά APIs"),
    ("Ειδοποιήσεις & Επικοινωνία", "Διαχείριση Κρατήσεων"),
    ("Ειδοποιήσεις & Επικοινωνία", "Πληρωμές & Τιμολόγια"),
    ("Εξωτερικά APIs", "Διαχείριση Κρατήσεων"),
    ("Εξωτερικά APIs", "Διαχείριση Συμβολαίων")
]

# Προσθήκη συνδέσεων
G.add_edges_from(edges)

# Σχεδίαση γραφήματος
plt.figure(figsize=(14, 10))
pos = nx.spring_layout(G, seed=42)  # Διάταξη των κόμβων
nx.draw(G, pos, with_labels=True, node_size=3500, node_color="lightblue", edge_color="gray", font_size=9, font_weight="bold", arrows=True)
plt.title("Σχεσιακό Διάγραμμα Interfaces του Συστήματος", fontsize=14)

# Αποθήκευση του διαγράμματος
plt.savefig("class_interfaces_diagram.png", format="png")
plt.show()

